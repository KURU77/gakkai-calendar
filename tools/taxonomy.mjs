function pick(nf, text) {
  const list = SUBS[nf];
  if (!list) return null;
  for (const [name, re] of list) if (re.test(text)) return name;
  return null;
}
export function refine(f, sf, text) {
  let nf = (MAP[f] || (() => f))(sf, text);
  if (nf === 'med' && /スポーツ|体力/.test(text)) nf = 'sport';
  let sub = pick(nf, text);
  if ((SUBS[nf] && !sub) || (f === 'soc' && sf === 'その他')) {
    for (const [g, re] of GLOBAL) if (g !== nf && re.test(text)) return [g, pick(g, text) || 'その他'];
  }
  if (!SUBS[nf]) return [nf, sf];
  return [nf, sub || 'その他'];
}
